import { useMemo, useState } from "react";
import {
  ArrowRight,
  BookOpen,
  CheckCircle2,
  CircleHelp,
  GitCompareArrows,
  Languages,
  Send,
  ShieldCheck,
  XCircle,
} from "lucide-react";
import {
  alphabetOf,
  grammarNfaAgreement,
  languageExamples,
  simulateNfa,
  stateLabel,
} from "../lib/automata";
import { deriveWord, generateStrings, grammarToText } from "../lib/grammar";
import { SAMPLES } from "../lib/data";
import { LAMBDA } from "../lib/types";
import {
  Badge,
  Card,
  Formula,
  PageHeader,
  TokenizedExpression,
} from "./ui";
import type { AppContext } from "./viewTypes";

export default function LanguageView({ ctx }: { ctx: AppContext }) {
  const [word, setWord] = useState("a");
  const alphabet = useMemo(() => alphabetOf(ctx.activeNfa, ctx.grammar), [ctx.activeNfa, ctx.grammar]);
  const examples = useMemo(() => languageExamples(ctx.activeNfa, alphabet, 4), [ctx.activeNfa, alphabet]);
  const generated = useMemo(() => generateStrings(ctx.grammar, 6, 10), [ctx.grammar]);
  const agreement = useMemo(
    () => grammarNfaAgreement(ctx.grammar, ctx.activeNfa, alphabet),
    [ctx.grammar, ctx.activeNfa, alphabet],
  );
  const membership = useMemo(() => ({
    automaton: simulateNfa(ctx.activeNfa, word),
    grammar: deriveWord(ctx.grammar, word, 14),
  }), [ctx.activeNfa, ctx.grammar, word]);
  const sample = SAMPLES.find((item) => item.id === ctx.sampleId);
  const mismatches = agreement.mismatches.length;

  const sendWord = (value: string) => {
    ctx.setSimulatorInput(value || LAMBDA);
    ctx.navigate("simulator");
  };

  return (
    <div className="fade-in">
      <PageHeader
        eyebrow="Module 08 · Formal language"
        title="Language Explorer"
        description="Compare the language generated by the grammar with the language accepted by the active NFA. Exact set notation and tested examples are shown; compact regular expressions are never asserted without proof."
        actions={
          <>
            <button className="btn btn-secondary" onClick={() => ctx.navigate("generator")}><Languages /> Generate strings</button>
            <button className="btn btn-primary" onClick={() => ctx.navigate("simulator")}>Open simulator <ArrowRight /></button>
          </>
        }
      />

      <div className="grid grid-cols-1 xl:grid-cols-12 gap-5">
        <div className="xl:col-span-8 space-y-5">
          <Card title="Mathematical description" subtitle="These statements are exact for the objects currently loaded.">
            <div className="space-y-3">
              <Formula caption="Definition by grammar derivation.">
                Σ = {"{"}{alphabet.join(", ") || "∅"}{"}"} &nbsp;·&nbsp; L(G) = {"{ w ∈ Σ* | "}{ctx.grammar.start || "S"}{" ⇒* w }"}
              </Formula>
              <Formula caption="Definition by the extended transition relation of the active λ-NFA.">
                L(M) = {"{ w ∈ Σ* | δ̂("}{stateLabel(ctx.activeNfa, ctx.activeNfa.startId)}{", w) ∩ F ≠ ∅ }"}
              </Formula>
            </div>
            <div className="notice notice-warning mt-4">
              <CircleHelp />
              <span>
                <strong>No unverified regular expression is claimed.</strong> A compact expression would require full state elimination plus an equivalence proof, or a certified preset annotation. The set-builder definitions above are exact; short-word tests below are evidence, not a proof of equality for all w.
              </span>
            </div>
            <div className="grid grid-cols-1 md:grid-cols-2 gap-3 mt-4">
              <div className="p-3 rounded-xl" style={{ background: "var(--surface-soft)", border: "1px solid var(--border)" }}>
                <div className="text-[10px] uppercase tracking-widest font-bold" style={{ color: "var(--faint)" }}>Informal description</div>
                <p className="text-[12px] mt-2 leading-relaxed" style={{ color: "var(--muted)" }}>
                  {sample ? sample.description : "Custom grammar: no instructor-verified informal description is attached. Use the examples, derivations, and automaton traces to characterise L(G)."}
                </p>
              </div>
              <div className="p-3 rounded-xl" style={{ background: "var(--surface-soft)", border: "1px solid var(--border)" }}>
                <div className="text-[10px] uppercase tracking-widest font-bold" style={{ color: "var(--faint)" }}>Automaton source</div>
                <div className="text-[13px] font-semibold mt-2">{ctx.activeNfaLabel}</div>
                <p className="text-[11px] mt-1" style={{ color: "var(--muted)" }}>F = {"{"}{ctx.activeNfa.finalIds.map((id) => stateLabel(ctx.activeNfa, id)).join(", ") || "∅"}{"}"}</p>
              </div>
            </div>
          </Card>

          <Card title="Membership checker" subtitle="Compare bounded derivation search with λ-NFA simulation for one word.">
            <div className="grid grid-cols-1 sm:grid-cols-[1fr_auto_auto] gap-3 items-end">
              <div>
                <label className="field-label" htmlFor="membership-word">Test word w (λ for empty)</label>
                <input id="membership-word" className="field field-math" value={word} spellCheck={false} onChange={(event) => setWord(event.target.value)} />
              </div>
              <button className="btn btn-secondary" onClick={() => setWord(LAMBDA)}>Use λ</button>
              <button className="btn btn-primary" onClick={() => sendWord(word)}><Send /> Simulate</button>
            </div>
            <div className="grid grid-cols-1 md:grid-cols-2 gap-3 mt-4">
              <div className={`notice ${membership.grammar.accepted ? "notice-success" : "notice-danger"}`}>
                {membership.grammar.accepted ? <CheckCircle2 /> : <XCircle />}
                <span><strong>Grammar derivation:</strong> {membership.grammar.accepted ? `accepted in ${membership.grammar.derivation.length - 1} rewrite(s).` : "not found."} {membership.grammar.reason}</span>
              </div>
              <div className={`notice ${membership.automaton.accepted ? "notice-success" : "notice-danger"}`}>
                {membership.automaton.accepted ? <CheckCircle2 /> : <XCircle />}
                <span><strong>Active NFA:</strong> {membership.automaton.accepted ? "accepted." : "rejected."} {membership.automaton.message}</span>
              </div>
            </div>
            {membership.grammar.accepted ? (
              <div className="flex flex-wrap items-center gap-2 mt-4 p-3 rounded-xl" style={{ background: "var(--surface-soft)", border: "1px solid var(--border)" }}>
                {membership.grammar.derivation.map((step, index) => (
                  <span key={`${step.form}-${index}`} className="flex items-center gap-2">
                    {index > 0 ? <span className="token-arrow math">⇒</span> : null}
                    <span className="pill-box math"><TokenizedExpression value={step.form || LAMBDA} /></span>
                  </span>
                ))}
              </div>
            ) : null}
          </Card>

          <Card title="Accepted and rejected samples" subtitle={`Exhaustive short-word testing over Σ, up to the bounded length used by the simulator (${examples.tested} words).`}>
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div>
                <div className="flex items-center gap-2 mb-2"><CheckCircle2 size={15} style={{ color: "var(--success)" }} /><span className="text-[12px] font-bold">Accepted by active NFA</span></div>
                <div className="flex flex-wrap gap-1.5 max-h-[190px] overflow-y-auto">
                  {examples.accepted.slice(0, 24).map((item) => (
                    <button key={`accepted-${item}`} className="badge badge-success math" onClick={() => setWord(item)}>{item}</button>
                  ))}
                  {examples.accepted.length === 0 ? <span className="text-xs" style={{ color: "var(--muted)" }}>No accepted words in tested range.</span> : null}
                </div>
              </div>
              <div>
                <div className="flex items-center gap-2 mb-2"><XCircle size={15} style={{ color: "var(--danger)" }} /><span className="text-[12px] font-bold">Rejected by active NFA</span></div>
                <div className="flex flex-wrap gap-1.5 max-h-[190px] overflow-y-auto">
                  {examples.rejected.slice(0, 24).map((item) => (
                    <button key={`rejected-${item}`} className="badge badge-danger math" onClick={() => setWord(item)}>{item}</button>
                  ))}
                </div>
              </div>
            </div>
            <div className="divider my-4" />
            <div className="text-[11px] font-bold mb-2" style={{ color: "var(--accent)" }}>Generated by grammar derivation</div>
            <div className="flex flex-wrap gap-1.5">
              {generated.strings.map((item) => (
                <button key={`generated-${item.value}`} className="badge badge-purple math" onClick={() => setWord(item.display)}>{item.display}</button>
              ))}
              {generated.strings.length === 0 ? <span className="text-xs" style={{ color: "var(--muted)" }}>No generated words at the current depth.</span> : null}
            </div>
          </Card>
        </div>

        <div className="xl:col-span-4 space-y-5">
          <Card title="Grammar ↔ NFA relationship" subtitle="The structural correspondence implemented in this lab.">
            <div className="table-scroll">
              <table className="data-table">
                <thead><tr><th>Grammar G</th><th>NFA M</th></tr></thead>
                <tbody>
                  <tr><td>Variable A ∈ V</td><td>State qA ∈ Q</td></tr>
                  <tr><td>Start symbol S</td><td>Initial state q₀</td></tr>
                  <tr><td>A → xB</td><td>Path qA ──x──→ qB</td></tr>
                  <tr><td>A → x</td><td>Path qA ──x──→ F</td></tr>
                  <tr><td>A → λ</td><td>λ-transition qA → F</td></tr>
                  <tr><td>Derivation S ⇒* w</td><td>Path q₀ ──w──→ qf ∈ F</td></tr>
                </tbody>
              </table>
            </div>
            <p className="text-[11px] mt-3 leading-relaxed" style={{ color: "var(--muted)" }}>
              The correspondence is an equivalence for right-linear grammars. Left-linear grammars describe the reversed path order and need the reversal construction.
            </p>
          </Card>

          <Card
            title="Bounded agreement audit"
            subtitle="Grammar derivation and NFA simulation are compared on short words."
            action={<Badge tone={mismatches ? "warning" : "success"} icon={mismatches ? undefined : ShieldCheck}>{agreement.matches}/{agreement.tested} match</Badge>}
          >
            <div className={`notice ${mismatches ? "notice-warning" : "notice-success"}`}>
              {mismatches ? <GitCompareArrows /> : <ShieldCheck />}
              <span>
                {mismatches
                  ? `${mismatches} mismatch(es) found in the tested sample: ${agreement.mismatches.slice(0, 8).map((item) => `“${item}”`).join(", ")}. This can be expected when a custom NFA is active or the grammar is not right-linear.`
                  : `All ${agreement.tested} tested words agree. This is bounded evidence over short words, not a proof for every w ∈ Σ*.`}
              </span>
            </div>
            <div className="progress-track mt-4">
              <div className="progress-fill" style={{ width: `${agreement.tested ? (agreement.matches / agreement.tested) * 100 : 0}%` }} />
            </div>
            <p className="text-[11px] mt-3" style={{ color: "var(--muted)" }}>Grammar membership uses bounded BFS (≤14 rewrites); NFA membership uses exact λ-closure simulation for the tested word.</p>
          </Card>

          <Card title="Current grammar" subtitle="Plain-text form of the productions used above.">
            <div className="code-box code-box-dark">{grammarToText(ctx.grammar) || "No productions"}</div>
            <div className="flex flex-wrap gap-2 mt-3">
              <Badge tone="blue"><BookOpen /> {ctx.analysis.label}</Badge>
              <Badge tone="purple">|Σ| = {alphabet.length}</Badge>
              <Badge tone="neutral">|F| = {ctx.activeNfa.finalIds.length}</Badge>
            </div>
            <button className="btn btn-secondary w-full mt-4" onClick={() => ctx.navigate("conversion")}>Review NFA construction <ArrowRight /></button>
          </Card>
        </div>
      </div>
    </div>
  );
}
